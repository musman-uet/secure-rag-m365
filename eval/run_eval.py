"""Retrieval quality + security evaluation.

Measures, on eval/golden_set.json:
  * Retrieval (per search mode): Hit@1, Recall@k, MRR, Precision@k
  * Security: permission leaks across EVERY user x EVERY question (must be 0)
  * End-to-end: answer status accuracy (answered / insufficient / conflicting)
    and citation correctness (answered questions cite a relevant document)

Run:  python -m securerag eval      (uses RAG_BACKEND=local by default)
"""

from __future__ import annotations

import json
from pathlib import Path

from securerag.config import ROOT, Settings
from securerag.directory import JsonDirectory
from securerag.factory import build_pipeline

GOLDEN = ROOT / "eval" / "golden_set.json"


def retrieval_metrics(pipeline, questions, directory, k: int, mode: str) -> dict:
    hit1 = recall = mrr = precision = 0.0
    n = 0
    for q in questions:
        relevant = set(q["relevant_doc_ids"])
        if not relevant:
            continue
        n += 1
        hits = pipeline.retrieve(q["question"], directory.get_user(q["user"]), top_k=k, mode=mode)
        docs = [h.chunk.doc_id for h in hits]
        hit1 += 1.0 if docs[:1] and docs[0] in relevant else 0.0
        recall += len(relevant & set(docs)) / len(relevant)
        precision += (sum(d in relevant for d in docs) / k) if docs else 0.0
        mrr += next((1.0 / r for r, d in enumerate(docs, start=1) if d in relevant), 0.0)
    return {"mode": mode, "n": n, "hit@1": hit1 / n, f"recall@{k}": recall / n,
            "mrr": mrr / n, f"precision@{k}": precision / n}


def security_check(pipeline, questions, directory, acl: dict[str, set[str]], k: int) -> dict:
    checks = leaks = 0
    examples = []
    for user in directory.all_users():
        principals = set(user.principals)
        for q in questions:
            for h in pipeline.retrieve(q["question"], user, top_k=k):
                checks += 1
                if not principals & acl[h.chunk.doc_id]:
                    leaks += 1
                    examples.append(f"{user.user_id} saw {h.chunk.doc_id} for {q['id']}")
    return {"retrieved_results_checked": checks, "leaks": leaks, "examples": examples[:5]}


def end_to_end(pipeline, questions, directory) -> dict:
    correct, rows, cite_ok, cite_n = 0, [], 0, 0
    for q in questions:
        a = pipeline.ask(q["question"], directory.get_user(q["user"]))
        ok = a.status.value == q["expected_status"]
        correct += ok
        if a.status.value in ("answered", "conflicting_evidence") and q["relevant_doc_ids"]:
            cite_n += 1
            cite_ok += any(c.doc_id in q["relevant_doc_ids"] for c in a.citations)
        rows.append((q["id"], q["user"], q["expected_status"], a.status.value, ok))
    return {"status_accuracy": correct / len(questions), "n": len(questions),
            "citation_accuracy": (cite_ok / cite_n) if cite_n else None, "rows": rows}


def to_markdown(backend: str, k: int, retrieval: list[dict], sec: dict, e2e: dict) -> str:
    lines = [f"# Evaluation results ({backend} backend)", "",
             f"Golden set: {e2e['n']} questions, 5 users. Generated by `python -m securerag eval`.", "",
             f"## Retrieval quality (answerable questions, k={k})", "",
             f"| Mode | Hit@1 | Recall@{k} | MRR | Precision@{k} |", "|---|---|---|---|---|"]
    for r in retrieval:
        lines.append(f"| {r['mode']} | {r['hit@1']:.2f} | {r[f'recall@{k}']:.2f} | {r['mrr']:.2f} | "
                     f"{r[f'precision@{k}']:.2f} |")
    lines += ["", f"Precision@{k} is low by construction: most questions have one relevant document,",
              f"and the top {k} results also contain other chunks.", "",
              "## Security trimming", "",
              f"- Retrieved results checked (every user x every question): {sec['retrieved_results_checked']}",
              f"- Permission leaks: **{sec['leaks']}**", "",
              "## End-to-end answers", "",
              f"- Status accuracy: **{e2e['status_accuracy']:.0%}** ({e2e['n']} questions)",
              f"- Citation accuracy (answers cite a correct document): **{e2e['citation_accuracy']:.0%}**", "",
              "| Question | User | Expected | Got | OK |", "|---|---|---|---|---|"]
    for qid, user, exp, got, ok in e2e["rows"]:
        lines.append(f"| {qid} | {user} | {exp} | {got} | {'yes' if ok else '**no**'} |")
    return "\n".join(lines) + "\n"


def run(settings: Settings, k: int = 5, out: str | None = "eval/results.md") -> int:
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))["questions"]
    manifest = json.loads(settings.manifest.read_text(encoding="utf-8"))
    acl = {d["doc_id"]: set(d["allowed_principals"]) for d in manifest["documents"]}
    directory = JsonDirectory(settings.directory)
    settings.audit_log = Path("/dev/null") if Path("/dev/null").exists() else settings.audit_log
    pipeline = build_pipeline(settings)

    retrieval = [retrieval_metrics(pipeline, golden, directory, k, m) for m in ("keyword", "vector", "hybrid")]
    sec = security_check(pipeline, golden, directory, acl, k)
    e2e = end_to_end(pipeline, golden, directory)
    report = to_markdown(settings.backend, k, retrieval, sec, e2e)
    print(report)
    if out:
        path = ROOT / out
        path.write_text(report, encoding="utf-8")
        print(f"Saved to {path}")
    return 1 if sec["leaks"] else 0
